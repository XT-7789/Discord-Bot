#!/bin/bash
BOT_DIR="$HOME/Discord-Bot"
cd "$BOT_DIR"

echo "[1/3] Copying updated files..."
cp /sdcard/Download/bot.py "$BOT_DIR/bot.py"
cp /sdcard/Download/suites.py "$BOT_DIR/suites.py"
cp /sdcard/Download/leveling.py "$BOT_DIR/leveling.py"
cp /sdcard/Download/economy_extra.py "$BOT_DIR/economy_extra.py"
cp /sdcard/Download/lounges.py "$BOT_DIR/lounges.py"
cp /sdcard/Download/counting.py "$BOT_DIR/counting.py"
cp /sdcard/Download/applications.py "$BOT_DIR/applications.py"
cp /sdcard/Download/staff_panel.py "$BOT_DIR/staff_panel.py"
cp /sdcard/Download/staff_sections.py "$BOT_DIR/staff_sections.py"
cp /sdcard/Download/economy.py "$BOT_DIR/economy.py"
rm -f "$BOT_DIR/tester_feedback.py"
cp /sdcard/Download/update_xp_rewards.py "$BOT_DIR/update_xp_rewards.py"
cp /sdcard/Download/update_economy_items.py "$BOT_DIR/update_economy_items.py"

echo "[2/3] Updating database (xp_rewards & economy items)..."
python3 "$BOT_DIR/update_xp_rewards.py"
python3 "$BOT_DIR/update_economy_items.py"

echo "[3/3] Starting bot..."
bash "$BOT_DIR/start.sh"
